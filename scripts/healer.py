"""Software Factory PR Auto-Healer & Feedback Loop.

Monitors pull requests generated by the factory, detects:
1. CI / Test failures (GitHub Actions workflows or Check Runs)
2. Review change requests (CHANGES_REQUESTED or unresolved review comments)

When an issue is detected:
- Formulates diagnostic feedback with exact errors and failed steps
- Sets the `software-factory/review` status to `failure` so OpenHands triggers a revision
- Tracks attempt count (default max: 3) to prevent infinite loops
- Escalates with `needs-human-attention` when retries are exhausted
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from typing import Any

from github_client import GitHubClient, GitHubError

MAX_RETRIES = 3
ATTEMPT_LABEL_RE = re.compile(r"^fix-attempt:(\d+)$")
ESCALATION_LABEL = "needs-human-attention"
TRIGGER_LABEL = "openhands"


@dataclass
class PRDiagnosis:
    pr_number: int
    head_sha: str
    branch: str
    status: str  # "HEALTHY", "PENDING", "CI_FAILED", "CHANGES_REQUESTED", "EXHAUSTED"
    attempt_count: int
    reasons: list[str] = field(default_factory=list)
    failed_checks: list[dict[str, Any]] = field(default_factory=list)
    reviews_feedback: list[dict[str, Any]] = field(default_factory=list)


def extract_attempt_count(labels: list[str], comments: list[dict[str, Any]] | None = None, head_sha: str | None = None) -> int:
    attempt = 0
    for lbl in labels:
        m = ATTEMPT_LABEL_RE.match(lbl)
        if m:
            try:
                attempt = int(m.group(1))
                break
            except ValueError:
                pass

    # If new commit was pushed since the last recorded heal comment, reset attempt count to 0
    if attempt > 0 and comments and head_sha:
        for c in reversed(comments):
            b = c.get("body") or ""
            if "Automated Healing & Revision Triggered" in b or "Automated Repair Limit Reached" in b:
                if head_sha[:7] not in b:
                    return 0
                break
    return attempt


def diagnose_pr(repo: str, pr: dict[str, Any], client: GitHubClient) -> PRDiagnosis:
    number = pr["number"]
    head_sha = pr["head"]["sha"]
    branch = pr["head"]["ref"]

    raw_labels = pr.get("labels", [])
    labels = [l.get("name", "") if isinstance(l, dict) else str(l) for l in raw_labels]

    # Fetch issue comments to inspect both attempt resets and gate blockers
    issue_comments: list[dict[str, Any]] = []
    try:
        issue_comments = client.list_comments(repo, number)
    except GitHubError:
        pass

    attempt = extract_attempt_count(labels, issue_comments, head_sha)

    # Check if escalation happened on the current head commit
    escalation_on_current_head = False
    if ESCALATION_LABEL in labels:
        for c in reversed(issue_comments):
            b = c.get("body") or ""
            if "Automated Repair Limit Reached" in b:
                if head_sha[:7] in b:
                    escalation_on_current_head = True
                break

    reasons: list[str] = []
    failed_checks: list[dict[str, Any]] = []
    reviews_feedback: list[dict[str, Any]] = []
    is_pending = False

    # 1. Inspect CI Check Runs
    try:
        check_runs = client.get_check_runs(repo, head_sha)
        for check in check_runs:
            c_name = check.get("name", "check")
            c_status = check.get("status")
            c_conclusion = check.get("conclusion")

            if c_status in ("queued", "in_progress"):
                is_pending = True
            elif c_conclusion in ("failure", "timed_out", "action_required", "cancelled"):
                output = check.get("output") or {}
                summary = output.get("summary") or output.get("title") or f"Check run {c_name} concluded with {c_conclusion}"
                reasons.append(f"CI Check `{c_name}` failed ({c_conclusion}): {summary[:200]}")
                failed_checks.append({
                    "name": c_name,
                    "conclusion": c_conclusion,
                    "html_url": check.get("html_url"),
                    "details": summary[:500],
                })
    except GitHubError:
        pass

    # 2. Inspect Workflow Runs (GitHub Actions)
    try:
        wf_runs = client.list_workflow_runs_for_commit(repo, head_sha)
        for wf in wf_runs:
            wf_name = wf.get("name", "Workflow")
            wf_status = wf.get("status")
            wf_conclusion = wf.get("conclusion")

            if wf_status in ("queued", "in_progress"):
                is_pending = True
            elif wf_conclusion in ("failure", "timed_out", "cancelled"):
                # Avoid duplicate if check_run already reported it
                if not any(fc["name"] == wf_name for fc in failed_checks):
                    msg = f"GitHub Actions workflow `{wf_name}` failed ({wf_conclusion})"
                    reasons.append(msg)
                    failed_checks.append({
                        "name": wf_name,
                        "conclusion": wf_conclusion,
                        "html_url": wf.get("html_url"),
                    })
    except GitHubError:
        pass

    # 3. Inspect PR Reviews (Latest review per reviewer)
    has_approved_review = False
    try:
        reviews = client.list_reviews(repo, number)
        latest_by_user: dict[str, dict[str, Any]] = {}
        for r in reviews:
            user = (r.get("user") or {}).get("login", "unknown")
            latest_by_user[user] = r

        for user, r in latest_by_user.items():
            state = r.get("state")
            body = (r.get("body") or "").strip()
            body_lower = body.lower()
            commit_id = r.get("commit_id")

            # Check if this review explicitly approved (by state or by verdict in body)
            is_approved = (
                state == "APPROVED"
                or bool(re.search(r"(?:verdict\s*[:\n]+.*?)?(?:✅\s*\*\*approved\*\*|✅\s*approved|\bverdict:\s*approved\b)", body, re.IGNORECASE))
                or ("code assessment: clean" in body_lower and "merge readiness: ready" in body_lower)
            )

            is_changes_requested = (
                not is_approved
                and (
                    state == "CHANGES_REQUESTED"
                    or (
                        state in ("COMMENTED", "CHANGES_REQUESTED")
                        and any(
                            phrase in body_lower
                            for phrase in (
                                "changes requested",
                                "changes_requested",
                                "blocking",
                                "needs changes",
                                "action required",
                                "configuration issue (blocking)",
                            )
                        )
                    )
                )
            )

            if is_approved:
                if commit_id == head_sha or not commit_id:
                    has_approved_review = True
                continue

            if is_changes_requested:
                desc = f"Reviewer @{user} requested changes"
                m = re.search(r"(\*\*🔄 CHANGES REQUESTED\*\*.*?)(?:\n\n|\Z)", body, re.DOTALL | re.IGNORECASE)
                if m:
                    desc += f": {m.group(1).strip()[:200]}"
                elif body:
                    desc += f": {body[:200]}"
                reasons.append(desc)
                reviews_feedback.append({
                    "author": user,
                    "state": state,
                    "body": body,
                    "html_url": r.get("html_url"),
                })
    except GitHubError:
        pass

    # 4. Inspect Review Comments (Inline code comments)
    try:
        comments = client.list_review_comments(repo, number)
        # Check comments only if there is no approved review on this commit,
        # and only look at comments originally authored on this exact head commit.
        if not has_approved_review and not reviews_feedback and not failed_checks:
            recent_comments = [
                c for c in comments
                if (c.get("original_commit_id") == head_sha or (not c.get("original_commit_id") and c.get("commit_id") == head_sha))
            ]
            if recent_comments:
                c_summaries = []
                for c in recent_comments[-3:]:
                    u = (c.get("user") or {}).get("login", "user")
                    p = c.get("path", "")
                    b = (c.get("body") or "").strip()
                    c_summaries.append(f"Comment by @{u} on `{p}`: {b[:120]}")
                if c_summaries:
                    reasons.extend(c_summaries)
                    reviews_feedback.extend(recent_comments)
    except GitHubError:
        pass

    # 4b. Inspect Issue Comments for Reviewer Gate Blockers
    for ic in issue_comments[-5:]:
        ic_body = (ic.get("body") or "").strip()
        if "review paused: current-head checks did not pass" in ic_body.lower():
            if head_sha[:7] in ic_body or head_sha[:12] in ic_body:
                msg = f"Review gate paused on `{head_sha[:7]}`: checks did not pass"
                if not any(fc.get("name") == "review-gate" for fc in failed_checks):
                    reasons.append(msg)
                    failed_checks.append({
                        "name": "review-gate",
                        "conclusion": "failure",
                        "details": ic_body[:300],
                    })

    # Determine overall status
    if failed_checks:
        status = "EXHAUSTED" if escalation_on_current_head else "CI_FAILED"
    elif reviews_feedback:
        status = "EXHAUSTED" if escalation_on_current_head else "CHANGES_REQUESTED"
    elif is_pending:
        status = "PENDING"
    else:
        status = "HEALTHY"

    return PRDiagnosis(
        pr_number=number,
        head_sha=head_sha,
        branch=branch,
        status=status,
        attempt_count=attempt,
        reasons=reasons,
        failed_checks=failed_checks,
        reviews_feedback=reviews_feedback,
    )


def heal_pr(
    repo: str,
    pr: dict[str, Any],
    diagnosis: PRDiagnosis,
    client: GitHubClient,
    max_retries: int = MAX_RETRIES,
    dry_run: bool = False,
) -> dict[str, Any]:
    number = pr["number"]
    head_sha = pr["head"]["sha"]
    branch = pr["head"]["ref"]

    raw_labels = pr.get("labels", [])
    labels = [l.get("name", "") if isinstance(l, dict) else str(l) for l in raw_labels]

    if diagnosis.status in ("HEALTHY", "PENDING", "EXHAUSTED"):
        # If PR became healthy on this SHA, cleanup any temporary attempt labels and set statuses to success
        if diagnosis.status == "HEALTHY":
            if not dry_run:
                had_fix_labels = any(ATTEMPT_LABEL_RE.match(l) for l in labels) or any(l in ("openhands-fix", ESCALATION_LABEL) for l in labels)
                for l in labels:
                    if ATTEMPT_LABEL_RE.match(l) or l in ("openhands-fix", ESCALATION_LABEL):
                        try:
                            client.remove_label(repo, number, l)
                        except Exception:
                            pass

                # Flag commit statuses as success for github-delivery-watchdog and GitHub UI
                client.create_commit_status(
                    repo=repo,
                    commit_sha=head_sha,
                    state="success",
                    context="software-factory/review",
                    description="Review passed: all criteria met",
                )
                client.create_commit_status(
                    repo=repo,
                    commit_sha=head_sha,
                    state="success",
                    context="software-factory/tests",
                    description="CI tests passing",
                )

                if had_fix_labels:
                    client.create_comment(
                        repo,
                        number,
                        f"### ✅ All Verifications Passed!\n\n"
                        f"All CI checks and reviews are now passing on commit `{head_sha[:7]}`.\n"
                        f"The pull request is clean and ready for automatic merge."
                    )
        return {
            "pr": number,
            "status": diagnosis.status,
            "action": "none",
            "reasons": diagnosis.reasons,
        }

    # Diagnosis is CI_FAILED or CHANGES_REQUESTED
    new_attempt = diagnosis.attempt_count + 1

    if new_attempt > max_retries:
        # Max retries exceeded -> escalate to human
        escalation_comment = (
            f"### 🚨 Automated Repair Limit Reached ({diagnosis.attempt_count}/{max_retries} Attempts)\n\n"
            f"OpenHands Software Factory attempted to automatically resolve this PR {diagnosis.attempt_count} time(s), "
            f"but tests or reviews are still failing on commit `{head_sha[:7]}`.\n\n"
            f"**Current Blockers:**\n"
            + "\n".join([f"- {r}" for r in diagnosis.reasons])
            + f"\n\n**Action Required:**\n"
            f"Please inspect the failures and resolve them manually. Label `{ESCALATION_LABEL}` has been attached."
        )

        if not dry_run:
            for l in labels:
                if ATTEMPT_LABEL_RE.match(l) or l == "openhands-fix":
                    client.remove_label(repo, number, l)
            client.add_labels(repo, number, [ESCALATION_LABEL])
            client.create_comment(repo, number, escalation_comment)

        return {
            "pr": number,
            "status": "ESCALATED",
            "action": "escalated_to_human",
            "attempt": diagnosis.attempt_count,
            "reasons": diagnosis.reasons,
        }

    # Trigger repair iteration
    reasons_md = "\n".join([f"- {r}" for r in diagnosis.reasons])
    heal_comment = (
        f"### 🔄 Automated Healing & Revision Triggered (Attempt {new_attempt}/{max_retries})\n\n"
        f"The factory detected the following issue(s) on commit `{head_sha[:7]}`:\n\n"
        f"{reasons_md}\n\n"
        f"**Actions Taken:**\n"
        f"- Flagged `software-factory/review` status as `failure` on `{head_sha[:7]}`.\n"
        f"- Assigned attempt label `fix-attempt:{new_attempt}`.\n"
        f"- Delegated revision task to OpenHands to check out `{branch}`, resolve the issues, and push an updated commit."
    )

    if not dry_run:
        # Update attempt labels
        for l in labels:
            if ATTEMPT_LABEL_RE.match(l):
                client.remove_label(repo, number, l)
        client.add_labels(repo, number, [f"fix-attempt:{new_attempt}", "openhands-fix"])

        clean_desc = re.sub(r"[\U00010000-\U0010ffff]", "", f"Auto-repair needed: {diagnosis.reasons[0]}").replace("*", "").strip()[:140]
        client.create_commit_status(
            repo=repo,
            commit_sha=head_sha,
            state="failure",
            context="software-factory/review",
            description=clean_desc,
        )
        if diagnosis.status == "CI_FAILED":
            client.create_commit_status(
                repo=repo,
                commit_sha=head_sha,
                state="failure",
                context="software-factory/tests",
                description="CI tests failing",
            )

        client.create_comment(repo, number, heal_comment)

    return {
        "pr": number,
        "status": diagnosis.status,
        "action": "revision_triggered",
        "attempt": new_attempt,
        "reasons": diagnosis.reasons,
    }


def scan_and_heal(
    repo: str,
    client: GitHubClient,
    branch_prefix: str = "openhands/issue",
    max_retries: int = MAX_RETRIES,
    dry_run: bool = False,
) -> dict[str, Any]:
    open_prs = client.list_pulls(repo, state="open")
    results = []

    for pr in open_prs:
        branch = pr.get("head", {}).get("ref", "")
        # Filter PRs belonging to our software factory
        if not branch.startswith(branch_prefix):
            continue

        diagnosis = diagnose_pr(repo, pr, client)
        outcome = heal_pr(repo, pr, diagnosis, client, max_retries=max_retries, dry_run=dry_run)
        results.append({
            "pr": pr["number"],
            "title": pr.get("title"),
            "branch": branch,
            "diagnosis": {
                "status": diagnosis.status,
                "reasons": diagnosis.reasons,
                "attempt": diagnosis.attempt_count,
            },
            "outcome": outcome,
        })

    return {
        "repo": repo,
        "scanned_prs": len(results),
        "healed": len([r for r in results if r["outcome"]["action"] == "revision_triggered"]),
        "escalated": len([r for r in results if r["outcome"]["action"] == "escalated_to_human"]),
        "results": results,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Software Factory PR Auto-Healer & Feedback Loop")
    parser.add_argument("--repos", required=True, help="Target repositories (owner/repo)")
    parser.add_argument("--branch-prefix", default="openhands/issue", help="PR branch prefix (default: openhands/issue)")
    parser.add_argument("--max-retries", type=int, default=MAX_RETRIES, help="Max repair attempts (default: 3)")
    parser.add_argument("--dry-run", action="store_true", help="Diagnose without making changes")
    args = parser.parse_args()

    client = GitHubClient()
    repos = [r.strip() for r in args.repos.split(",") if r.strip()]
    all_res = {}

    for repo in repos:
        try:
            res = scan_and_heal(
                repo=repo,
                client=client,
                branch_prefix=args.branch_prefix,
                max_retries=args.max_retries,
                dry_run=args.dry_run,
            )
            all_res[repo] = res
        except Exception as err:
            all_res[repo] = {"error": str(err)}

    print(json.dumps(all_res, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
